"""Build eval/report.md from eval/results.json (written by web/app/eval/eval.ts).

Quality bars were fixed before the run (decision 41, eval/thresholds.yaml):
  - accuracy: |tool - expert| long axis within the LIDC inter-reader spread
  - repeatability: |test - retest| long axis <= ~1 mm (Daniel's own repeatability)
Time saved is a MODEL from Daniel's per-step minutes and the measured rates below;
the timed study (decision 43) is pending and must be run by a human.
"""
import json, pathlib, statistics as st

R = json.loads((pathlib.Path(__file__).parent / "results.json").read_text())
ms, mt = R["measurements"], R["matching"]


def f(x, d=1):
    return "–" if x is None else f"{x:.{d}f}"


lines = ["# LongMarker — evaluation report", "",
         "Generated by `eval/report.py` from `eval/results.json`. Research use only.",
         "Seeds simulate Daniel's click: an expert-outlined voxel next to the nodule centre. "
         "The same TypeScript code that runs in the browser produced every number here.", ""]

# --- per nodule table ---
lines += ["## Per nodule: tool vs expert", "",
          "| Case | Type / teaching case | Tool long × short (mm) | Expert long × short (mm) | Δ long (mm) | Tool vol (cm³) | Expert vol (cm³) | Dice | Flagged uncertain | Time (ms) |",
          "|---|---|---|---|---|---|---|---|---|---|"]
dl = []
for m in ms:
    t, e = m["tool"], m["expert"]
    d = (t["long"] - e["long"]) if t and e else None
    if d is not None:
        dl.append((m, d))
    lines.append(f"| {m['case_id']}#{m['nodule']} | {m.get('teaching_case') or m['source']} | "
                 f"{f(t and t['long'])} × {f(t and t['short'])} | {f(e and e['long'])} × {f(e and e['short'])} | {f(d)} | "
                 f"{f(t and t['vol'] / 1000, 2)} | {f(e and e['vol'] / 1000, 2)} | {f(m['dice'], 2)} | {'yes' if m['uncertain'] else ''} | {m['ms']} |")

# --- accuracy vs inter-reader spread (LIDC) ---
lines += ["", "## Accuracy vs inter-reader spread (LIDC, decision 38)", "",
          "| Nodule | Readers | Reader long-axis range (mm) | Tool long (mm) | Inside reader range ±0.5 mm? |", "|---|---|---|---|---|"]
inside = tot = 0
for m in ms:
    if m["source"] != "LIDC" or not m["readers"] or not m["tool"]:
        continue
    rl = [r["long"] for r in m["readers"]]
    lo, hi = min(rl), max(rl)
    ok = lo - 0.5 <= m["tool"]["long"] <= hi + 0.5
    inside += ok; tot += 1
    lines.append(f"| {m['case_id']}#{m['nodule']} ({m.get('teaching_case')}) | {len(rl)} | {lo:.1f}–{hi:.1f} | {m['tool']['long']:.1f} | {'✅' if ok else '❌'} |")
if tot:
    lines.append(f"\n**{inside}/{tot}** LIDC nodules: the tool's long axis falls inside the range of the radiologists' own outlines.")

# --- repeatability (RIDER test-retest) ---
lines += ["", "## Repeatability: same-day test vs retest (RIDER, decision 39)", "",
          "| Patient | Tool long test / retest (mm) | |Δ| tool | Expert long test / retest (mm) | |Δ| expert |", "|---|---|---|---|---|"]
by = {}
for m in ms:
    if m["source"] == "RIDER" and m["tool"]:
        by.setdefault(m["patient_id"], {})[m["timepoint"]] = m
rep_t, rep_e = [], []
for p, d in sorted(by.items()):
    if "test" in d and "retest" in d:
        a, b = d["test"], d["retest"]
        dt = abs(a["tool"]["long"] - b["tool"]["long"])
        de = abs(a["expert"]["long"] - b["expert"]["long"]) if a["expert"] and b["expert"] else None
        rep_t.append(dt)
        if de is not None:
            rep_e.append(de)
        lines.append(f"| {p} | {a['tool']['long']:.1f} / {b['tool']['long']:.1f} | {dt:.1f} | "
                     f"{f(a['expert'] and a['expert']['long'])} / {f(b['expert'] and b['expert']['long'])} | {f(de)} |")
if rep_t:
    lines.append(f"\nMedian |Δ long|: tool **{st.median(rep_t):.1f} mm**, expert {f(st.median(rep_e) if rep_e else None)} mm "
                 f"(the tumour does not change in 15 minutes, so any difference is measurement noise).")

# --- matching ---
lines += ["", "## Follow-up matching (decisions 24–27)", "",
          "| Baseline → follow-up | Registration error (mm) | Found | Correct nodule | Flagged for confirmation |", "|---|---|---|---|---|"]
for x in mt:
    lines.append(f"| {x['baseline']} → {x['followup']} | {x['predicted_error_mm']} | {'yes' if x['found'] else 'no'} | {'✅' if x['correct'] else '❌'} | {'yes' if x['uncertain'] else ''} |")
n_ok = sum(x["correct"] for x in mt)
if mt:
    lines.append(f"\n**{n_ok}/{len(mt)}** follow-up nodules landed on the right nodule. Note: RIDER pairs are same-day scans, "
                 "which flatters registration; a months-apart follow-up will be harder.")

# --- summary + time model ---
unc = sum(m["uncertain"] for m in ms) / max(1, len(ms))
good = [d for m, d in dl if abs(d) <= max(1.5, 0.1 * m["expert"]["long"])]
lines += ["", "## Summary", "",
          f"- Nodules measured: {len(ms)}; flagged uncertain: {unc:.0%} (these need Daniel's correction).",
          f"- Long axis within max(1.5 mm, 10%) of the expert: {len(good)}/{len(dl)}.",
          f"- Median outline time per click: {st.median([m['ms'] for m in ms]):.0f} ms (node; browser is similar)."]

# time model (minutes), Daniel's numbers: finding 10–20, measuring 2–4 per nodule, recording 3–5, matching ~10 on follow-ups
nod = 1.5
man_base = 15 + 3 * nod + 4
man_fu = man_base + 10
corr = unc  # share of nodules needing a manual correction
tool_meas = nod * (0.5 + corr * 2.0)  # click + review, +2 min when a correction is needed
tool_rec = 0.5
match_rate = n_ok / max(1, len(mt))
tool_match = 1.0 * match_rate + 10 * (1 - match_rate)
tool_find_fu = 15 * 0.6  # known nodules are jumped to; Daniel still pages through for new ones
tool_base = 15 + tool_meas + tool_rec
tool_fu = tool_find_fu + tool_meas + tool_rec + tool_match
lines += ["", "## Time saved — model (not a measurement)", "",
          "Inputs: Daniel's own minutes per step, 1.5 nodules per scan, and the rates measured above. "
          "No detector is used, so baseline finding is unchanged.", "",
          "| Step | Manual baseline | Tool baseline | Manual follow-up | Tool follow-up |", "|---|---|---|---|---|",
          f"| Finding | 15 | 15 | 15 | {tool_find_fu:.0f} (known nodules located automatically) |",
          f"| Measuring (1.5 nodules) | {3 * nod:.1f} | {tool_meas:.1f} | {3 * nod:.1f} | {tool_meas:.1f} |",
          f"| Recording | 4 | {tool_rec} | 4 | {tool_rec} |",
          f"| Matching | – | – | 10 | {tool_match:.1f} |",
          f"| **Total** | **{man_base:.1f}** | **{tool_base:.1f}** (−{1 - tool_base / man_base:.0%}) | **{man_fu:.1f}** | **{tool_fu:.1f}** (−{1 - tool_fu / man_fu:.0%}) |", "",
          "The timed study (decision 43) is still to be run by a person: ~10 cases, manual vs tool in alternating order, "
          "using the built-in per-case timer (`minutes` column in the CSV export). Protocol: `eval/timed-study.md`."]

(pathlib.Path(__file__).parent / "report.md").write_text("\n".join(lines) + "\n")
print("\n".join(lines[-12:]))
