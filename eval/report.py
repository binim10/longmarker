"""Build eval/report.md from eval/results.json (written by web/app/eval/eval.ts).

Quality bars were fixed before the run (decision 41, eval/thresholds.yaml):
  - accuracy: |tool - expert| long axis within the LIDC inter-reader spread
  - repeatability: |test - retest| long axis <= ~1 mm (Daniel's own repeatability)
Time saved is a MODEL from Daniel's per-step minutes and the measured rates below;
the timed study (decision 43) is pending and must be run by a human.
"""
import json, pathlib, statistics as st

R = json.loads((pathlib.Path(__file__).parent / "results.json").read_text())
ms, mt = R["measurements"], R["matching"]


def f(x, d=1):
    return "–" if x is None else f"{x:.{d}f}"


lines = ["# LongMarker — evaluation report", "",
         "Generated by `eval/report.py` from `eval/results.json`. Research use only.",
         "Seeds simulate Daniel's click: an expert-outlined voxel next to the nodule centre. "
         "The same TypeScript code that runs in the browser produced every number here.", "",
         "**Caveat:** the default threshold was calibrated on RIDER test scans only, but the retry heuristics "
         "(GGO order, 3D opening, >30 mm flag) were developed while looking at these same 21 nodules. "
         "There is no unseen hold-out set, so treat these numbers as optimistic.", ""]

# --- per nodule table ---
lines += ["## Per nodule: tool vs expert", "",
          "| Case | Type / teaching case | Tool long × short (mm) | Expert long × short (mm) | Δ long (mm) | Tool vol (cm³) | Expert vol (cm³) | Dice | Flagged uncertain | Time (ms) |",
          "|---|---|---|---|---|---|---|---|---|---|"]
dl = []
for m in ms:
    t, e = m["tool"], m["expert"]
    d = (t["long"] - e["long"]) if t and e else None
    if d is not None:
        dl.append((m, d))
    lines.append(f"| {m['case_id']}#{m['nodule']} | {m.get('teaching_case') or m['source']} | "
                 f"{f(t and t['long'])} × {f(t and t['short'])} | {f(e and e['long'])} × {f(e and e['short'])} | {f(d)} | "
                 f"{f(t and t['vol'] / 1000, 2)} | {f(e and e['vol'] / 1000, 2)} | {f(m['dice'], 2)} | {'yes' if m['uncertain'] else ''} | {m['ms']} |")

# --- accuracy vs inter-reader spread (LIDC) ---
lines += ["", "## Accuracy vs inter-reader spread (LIDC, decision 38)", "",
          "| Nodule | Readers | Reader long-axis range (mm) | Tool long (mm) | Inside reader range ±0.5 mm? |", "|---|---|---|---|---|"]
inside = tot = 0
for m in ms:
    if m["source"] != "LIDC" or not m["readers"] or not m["tool"]:
        continue
    rl = [r["long"] for r in m["readers"]]
    lo, hi = min(rl), max(rl)
    ok = lo - 0.5 <= m["tool"]["long"] <= hi + 0.5
    inside += ok; tot += 1
    lines.append(f"| {m['case_id']}#{m['nodule']} ({m.get('teaching_case')}) | {len(rl)} | {lo:.1f}–{hi:.1f} | {m['tool']['long']:.1f} | {'✅' if ok else '❌'} |")
if tot:
    lines.append(f"\n**{inside}/{tot}** LIDC nodules: the tool's long axis falls inside the range of the radiologists' own outlines.")

# --- repeatability (RIDER test-retest) ---
lines += ["", "## Repeatability: same-day test vs retest (RIDER, decision 39)", "",
          "| Patient | Tool long test / retest (mm) | |Δ| tool | Expert long test / retest (mm) | |Δ| expert |", "|---|---|---|---|---|"]
by = {}
for m in ms:
    if m["source"] == "RIDER" and m["tool"]:
        by.setdefault(m["patient_id"], {})[m["timepoint"]] = m
rep_t, rep_e = [], []
for p, d in sorted(by.items()):
    if "test" in d and "retest" in d:
        a, b = d["test"], d["retest"]
        dt = abs(a["tool"]["long"] - b["tool"]["long"])
        de = abs(a["expert"]["long"] - b["expert"]["long"]) if a["expert"] and b["expert"] else None
        rep_t.append(dt)
        if de is not None:
            rep_e.append(de)
        lines.append(f"| {p} | {a['tool']['long']:.1f} / {b['tool']['long']:.1f} | {dt:.1f} | "
                     f"{f(a['expert'] and a['expert']['long'])} / {f(b['expert'] and b['expert']['long'])} | {f(de)} |")
if rep_t:
    lines.append(f"\nMedian |Δ long|: tool **{st.median(rep_t):.1f} mm**, expert {f(st.median(rep_e) if rep_e else None)} mm "
                 f"(the tumour does not change in 15 minutes, so any difference is measurement noise).")

# --- matching ---
lines += ["", "## Follow-up matching (decisions 24–27)", "",
          "| Baseline → follow-up | Registration error (mm) | Found | Correct nodule | Flagged for confirmation |", "|---|---|---|---|---|"]
for x in mt:
    lines.append(f"| {x['baseline']} → {x['followup']} | {x['predicted_error_mm']} | {'yes' if x['found'] else 'no'} | {'✅' if x['correct'] else '❌'} | {'yes' if x['uncertain'] else ''} |")
n_ok = sum(x["correct"] for x in mt)
if mt:
    n_flag = sum(x["uncertain"] for x in mt)
    lines.append(f"\n**{n_ok}/{len(mt)}** follow-up nodules landed on the right nodule. **What “correct” means here:** the outline "
                 "Find produced overlaps the expert’s follow-up mask by at least one voxel. That is a lenient test of landing on "
                 "the right nodule, not of outline quality, which the tables above report separately. "
                 f"**{n_flag} of {len(mt)}** matches were flagged for Daniel to confirm. Note: RIDER pairs are same-day scans, "
                 "which flatters registration; a months-apart follow-up will be harder.")

# --- experimental detection (decisions 28-30, J14) ---
det_p = pathlib.Path(__file__).parent / "detection.json"
if det_p.exists():
    D = json.loads(det_p.read_text())
    lines += ["", "## Experimental candidate detection (decisions 28–30)", "",
              "Classical Hessian dot filter, parameters fixed before scoring (`pipeline/detect.py`), top 10 per scan, no training.", "",
              "| Teaching case / source | Nodules | Found in top 5 | Found in top 10 |", "|---|---|---|---|"]
    groups = {}
    for r in D:
        groups.setdefault(r["teaching_case"] or r["source"], []).append(r)
    for g, rs in sorted(groups.items()):
        lines.append(f"| {g} | {len(rs)} | {sum(1 for r in rs if r['hit_rank'] and r['hit_rank'] <= 5)} | {sum(1 for r in rs if r['hit_rank'])} |")
    n = len(D); h5 = sum(1 for r in D if r["hit_rank"] and r["hit_rank"] <= 5); h10 = sum(1 for r in D if r["hit_rank"])
    scans = len({r["case_id"] for r in D})
    lines.append(f"\n**Sensitivity {h5}/{n} at 5 and {h10}/{n} at 10 candidates, ~{(10 * scans - h10) / scans:.1f} false candidates per scan.** "
                 "It misses ground-glass and large tumours. This does not meet the bar, so per decision 30 it ships as an *experimental*, "
                 "off-by-default jump list, and the time model does not count on it.")

# --- summary + time model ---
unc = sum(m["uncertain"] for m in ms) / max(1, len(ms))
good = [d for m, d in dl if abs(d) <= max(1.5, 0.1 * m["expert"]["long"])]
lines += ["", "## Summary", "",
          f"- Nodules measured: {len(ms)}; flagged uncertain: {unc:.0%} (these need Daniel's correction).",
          f"- Long axis within max(1.5 mm, 10%) of the expert: {len(good)}/{len(dl)}.",
          f"- Off by more than that **and not flagged** (silent errors — the dangerous kind): "
          f"{sum(1 for m, d in dl if abs(d) > max(1.5, 0.1 * m['expert']['long']) and not m['uncertain'])}/{len(dl)}: "
          + ", ".join(f"{m['case_id']}#{m['nodule']} ({d:+.1f} mm)" for m, d in dl if abs(d) > max(1.5, 0.1 * m['expert']['long']) and not m['uncertain']) + ".",
          f"- Median outline time per click: {st.median([m['ms'] for m in ms]):.0f} ms (node; browser is similar)."]

# time model (minutes), Daniel's numbers: finding 10–20, measuring 2–4 per nodule, recording 3–5, matching ~10 on follow-ups
nod = 1.5
man_base = 15 + 3 * nod + 4
man_fu = man_base + 10
silent = sum(1 for m, d in dl if abs(d) > max(1.5, 0.1 * m['expert']['long']) and not m['uncertain']) / max(1, len(dl))
corr = unc + silent  # share of nodules needing a manual correction (flagged + silent)
tool_meas = nod * (0.5 + corr * 2.0)  # click + review, +2 min when a correction is needed
tool_rec = 0.5
match_rate = n_ok / max(1, len(mt))
unc_match = sum(x['uncertain'] for x in mt) / max(1, len(mt))
tool_match = match_rate * (1.0 + 2.0 * unc_match) + 10 * (1 - match_rate)  # +2 min to confirm a flagged match
tool_find_fu = 15 * 0.6  # known nodules are jumped to; Daniel still pages through for new ones
tool_base = 15 + tool_meas + tool_rec
tool_fu = tool_find_fu + tool_meas + tool_rec + tool_match
lines += ["", "## Time saved — model (not a measurement)", "",
          "Inputs: Daniel's own minutes per step, 1.5 nodules per scan, and the rates measured above. "
          "No detector is used, so baseline finding is unchanged.", "",
          "| Step | Manual baseline | Tool baseline | Manual follow-up | Tool follow-up |", "|---|---|---|---|---|",
          f"| Finding | 15 | 15 | 15 | {tool_find_fu:.0f} (known nodules located automatically) |",
          f"| Measuring (1.5 nodules) | {3 * nod:.1f} | {tool_meas:.1f} | {3 * nod:.1f} | {tool_meas:.1f} |",
          f"| Recording | 4 | {tool_rec} | 4 | {tool_rec} |",
          f"| Matching | – | – | 10 | {tool_match:.1f} |",
          f"| **Total** | **{man_base:.1f}** | **{tool_base:.1f}** (−{1 - tool_base / man_base:.0%}) | **{man_fu:.1f}** | **{tool_fu:.1f}** (−{1 - tool_fu / man_fu:.0%}) |", "",
          f"**Sensitivity:** the biggest single saving is the assumption that *Find* shortens the follow-up search to 60% of 15 min. "
          f"Without it (finding stays 15 min) the follow-up total is {tool_fu + 15 - tool_find_fu:.1f} min "
          f"(−{1 - (tool_fu + 15 - tool_find_fu) / man_fu:.0%}). So 'roughly halved' depends on that assumption; the timed study must confirm it.", "",
          "The timed study (decision 43) is still to be run by a person: ~10 cases, manual vs tool in alternating order, "
          "using the built-in per-case timer (`minutes` column in the CSV export). Protocol: `eval/timed-study.md`."]

# --- interaction-count estimate (decision 43, agent-run; NOT a human-timed study) ---
# KLM operator times, Card, Moran & Newell (1980): P point 1.1 s, B button press+release 0.2 s,
# M mental preparation 1.35 s. Brush correction per slice is not a KLM operator: parameter 5-15 s,
# plus 0.5 s to scroll to the slice. Manual side = Daniel's own minutes (client data).
P, B, M, SCROLL = 1.1, 0.2, 1.35, 0.5
def tool_nodule_s(m, brush):
    t = (P + B) + M + (P + B)                      # click nodule, review numbers, Save
    if m["uncertain"]:
        t += M + (P + B) + P                       # read the reason, adjust threshold slider
    c = m.get("slices_to_correct") or 0
    t += c * (brush + SCROLL)                       # brush correction on each disagreeing slice
    return t
match_by_fu = {x["followup"]: x for x in mt}
def scan_minutes(case_ms, followup, brush, find_factor):
    s_ = sum(tool_nodule_s(m, brush) for m in case_ms) + M   # + one check of the auto-filled row
    if followup:
        x = match_by_fu.get(case_ms[0]["case_id"])
        s_ += (P + B) + M + ((M + 3) if x and x["uncertain"] else 0) - (P + B)  # Find replaces the click; confirm
        find = 15 * find_factor
    else:
        find = 15
    return find + s_ / 60
by_case = {}
for m in ms:
    by_case.setdefault(m["case_id"], []).append(m)
rows_t = []
for cid, cm in sorted(by_case.items()):
    fu = cm[0]["source"] == "RIDER" and cm[0]["timepoint"] == "retest"
    n = len(cm)
    manual = 15 + 3 * n + 4 + (10 if fu else 0)
    rows_t.append(dict(case=cid, fu=fu, n=n, manual=manual,
                       lo=scan_minutes(cm, fu, 5, 0.6 if fu else 1), hi=scan_minutes(cm, fu, 15, 0.6 if fu else 1),
                       hi_nofind=scan_minutes(cm, fu, 15, 1.0), slices=sum((m.get("slices_to_correct") or 0) for m in cm)))
med = lambda xs: st.median(xs) if xs else float("nan")
lines += ["", "## Interaction-count estimate (decision 43): agent-run, NOT a human-timed study", "",
          "What was counted on these exact cases: clicks, reviews, flagged items, and **axial slices needing a brush correction** "
          "(tool vs expert area differs by >20% of the larger, threshold fixed before computing). Converted with KLM operator times "
          "(Card, Moran & Newell 1980: point 1.1 s, button 0.2 s, mental 1.35 s); brush correction 5–15 s per slice + 0.5 s scroll. "
          "Manual side = Daniel's own minutes. Finding (visual search) cannot be modelled this way and stays at Daniel's 15 min; "
          "the follow-up columns also show the 'Find shortens the search to 60%' assumption separately.", "",
          "| Case | Nodules | Slices to correct | Manual (Daniel) | Tool, 5 s/slice | Tool, 15 s/slice | Tool, 15 s/slice, no Find-search saving |",
          "|---|---|---|---|---|---|---|"]
for r in rows_t:
    lines.append(f"| {r['case']}{' (follow-up)' if r['fu'] else ''} | {r['n']} | {r['slices']} | {r['manual']:.1f} | {r['lo']:.1f} | {r['hi']:.1f} | {r['hi_nofind']:.1f} |")
for label, sel in [("Baseline scans", lambda r: not r["fu"]), ("Follow-up scans", lambda r: r["fu"])]:
    R_ = [r for r in rows_t if sel(r)]
    mm, l, h, hn = med([r["manual"] for r in R_]), med([r["lo"] for r in R_]), med([r["hi"] for r in R_]), med([r["hi_nofind"] for r in R_])
    lines.append(f"\n**{label}** (median of {len(R_)}): manual {mm:.1f} min → tool {l:.1f}–{h:.1f} min "
                 f"(−{1 - h / mm:.0%} to −{1 - l / mm:.0%}); without the Find-search saving {hn:.1f} min (−{1 - hn / mm:.0%}).")
lines.append("\nRead this as an upper bound on interaction savings for an expert user; the person-timed study (eval/timed-study-cases.md) is still the stronger evidence. "
             "Large central tumours are the exception: 24–97 slices to correct can make the tool *slower* than Daniel's own measuring.")

(pathlib.Path(__file__).parent / "report.md").write_text("\n".join(lines) + "\n")
print("\n".join(lines[-12:]))
